// Generate protocol bindings and policy/transition metadata from the canonical sources.
import { readFile, writeFile } from 'node:fs/promises';
import { spawnSync } from 'node:child_process';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { FetchingJSONSchemaStore, InputData, JSONSchemaInput, quicktype } from 'quicktype-core';

const root = fileURLToPath(new URL('../', import.meta.url));
const readJson = async (relative) => JSON.parse(await readFile(path.join(root, relative), 'utf8'));
const [schema, lifecycle, peerPolicy, errorPolicy] = await Promise.all([
  readJson('schemas/run-protocol.schema.json'),
  readJson('schemas/lifecycle-transitions.json'),
  readJson('schemas/peer-policy.json'),
  readJson('schemas/error-policy.json'),
]);
const check = process.argv.includes('--check');
const schemaDefs = schema.$defs;
const rootKinds = Object.fromEntries(schema.oneOf.map(({ $ref }) => {
  const name = $ref.split('/').at(-1);
  return [name.replace(/Message$/, '').toLowerCase(), schemaDefs[name]];
}));

function collectVariants(definition) {
  if (!definition || typeof definition !== 'object') return [];
  const own = definition.properties?.variant?.const;
  return [...(own ? [own] : []), ...(definition.oneOf ?? []).flatMap((part) => collectVariants(part.$ref ? schemaDefs[part.$ref.split('/').at(-1)] : part)), ...(definition.allOf ?? []).flatMap((part) => collectVariants(part.$ref ? schemaDefs[part.$ref.split('/').at(-1)] : part))];
}

const variants = Object.fromEntries(Object.entries(rootKinds).map(([kind, definition]) => [kind, [...new Set(collectVariants(definition))]]));
for (const variant of variants.command) {
  if (!Array.isArray(peerPolicy.messages.command[variant])) throw new Error(`Missing peer policy for command ${variant}`);
}
if (Object.keys(peerPolicy.messages.command).some((variant) => !variants.command.includes(variant))) throw new Error('Peer policy contains an unknown command variant');
for (const kind of ['event', 'response', 'error']) {
  if (!Array.isArray(peerPolicy.messages[kind]['*'])) throw new Error(`Missing wildcard peer policy for ${kind}`);
}
const errorCodes = schemaDefs.ErrorCode.enum;
if (Object.keys(errorPolicy.retry).sort().join('\n') !== [...errorCodes].sort().join('\n')) throw new Error('Error policy and ErrorCode schema have different variants');

const transitions = [];
const seen = new Set();
const lifecycleEventEntities = new Map();
for (const entity of lifecycle.entities) {
  const states = new Set(entity.states);
  for (const transition of entity.transitions) {
    const { from, to, events } = transition;
    if (!states.has(from) || !states.has(to)) throw new Error(`Unknown ${entity.name} state in ${from} -> ${to}`);
    const key = `${entity.name}\0${from}\0${to}`;
    if (seen.has(key)) throw new Error(`Duplicate transition ${entity.name} ${from} -> ${to}`);
    seen.add(key);
    for (const event of events) {
      if (!variants.event.includes(event)) throw new Error(`Transition maps to unknown event ${event}`);
      const previousEntity = lifecycleEventEntities.get(event);
      if (previousEntity && previousEntity !== entity.name) throw new Error(`Lifecycle event ${event} maps to multiple entities: ${previousEntity}, ${entity.name}`);
      lifecycleEventEntities.set(event, entity.name);
    }
    transitions.push({ entity: entity.name, ...transition });
  }
}

const quoteRust = (value) => JSON.stringify(value);
const formatRust = (source) => {
  const result = spawnSync('rustfmt', ['--edition', '2021', '--emit', 'stdout'], { input: source, encoding: 'utf8' });
  if (result.error || result.status !== 0) throw new Error(result.error ?? `rustfmt exited with status ${result.status}`);
  return result.stdout;
};
const knownArms = Object.entries(variants).flatMap(([kind, names]) => names.map((variant) => `        (${quoteRust(kind)}, ${quoteRust(variant)})`)).join(' |\n');
const roleArms = Object.entries(peerPolicy.messages).flatMap(([kind, policy]) => Object.entries(policy).flatMap(([variant, roles]) => {
  const variantsForKind = variant === '*' ? variants[kind] : [variant];
  return variantsForKind.map((name) => `        (${quoteRust(kind)}, ${quoteRust(name)}, role) if [${roles.map(quoteRust).join(', ')}].contains(&role) => true,`);
})).join('\n');
const errorArms = errorCodes.map((code) => `        ${quoteRust(code)}`).join(' |\n');
const retryArms = Object.entries(errorPolicy.retry).map(([code, advice]) => `        ${quoteRust(code)} => Some(${quoteRust(advice)}),`).join('\n');
const metadataRust = `// Generated by scripts/generate-protocol.mjs; do not edit.\n\
pub const MAX_RAW_MESSAGE_BYTES: usize = 1_048_576;\n\
pub const MAX_CONTAINER_DEPTH: usize = 32;\n\
pub const U64_MAX: &str = "18446744073709551615";\n\
pub const U128_MAX: &str = "340282366920938463463374607431768211455";\n\
pub fn is_known_variant(kind: &str, variant: &str) -> bool {\n    matches!((kind, variant),\n${knownArms}\n    )\n}\n\n\
pub fn peer_role_allowed(kind: &str, variant: &str, role: &str) -> bool {\n    match (kind, variant, role) {\n${roleArms}\n        _ => false,\n    }\n}\n\n\
pub fn is_error_code(code: &str) -> bool {\n    matches!(code,\n${errorArms}\n    )\n}\n\n\
pub fn retry_advice(code: &str) -> Option<&'static str> {\n    match code {\n${retryArms}\n        _ => None,\n    }\n}\n`;

const transitionArms = transitions.map(({ entity, from, to }) => `        (${quoteRust(entity)}, ${quoteRust(from)}, ${quoteRust(to)})`).join(' |\n');
const eventArms = transitions.map(({ entity, from, to, events }) => `        (${quoteRust(entity)}, ${quoteRust(from)}, ${quoteRust(to)}) => Some(&[${events.map(quoteRust).join(', ')}]),`).join('\n');
const lifecycleEntityArms = [...lifecycleEventEntities].map(([event, entity]) => `        ${quoteRust(event)} => Some(${quoteRust(entity)}),`).join('\n');
const transitionsRust = `// Generated by scripts/generate-protocol.mjs; do not edit.\n\
pub const TRANSITION_COUNT: usize = ${transitions.length};\n\n\
pub fn lifecycle_entity_for_event(event: &str) -> Option<&'static str> {\n    match event {\n${lifecycleEntityArms}\n        _ => None,\n    }\n}\n\n\
pub fn can_transition(entity: &str, from: &str, to: &str) -> bool {\n    matches!((entity, from, to),\n${transitionArms}\n    )\n}\n\n\
pub fn transition_events(entity: &str, from: &str, to: &str) -> Option<&'static [&'static str]> {\n    match (entity, from, to) {\n${eventArms}\n        _ => None,\n    }\n}\n`;
const transitionsTs = `// Generated by scripts/generate-protocol.mjs; do not edit.\nexport const TRANSITION_COUNT = ${transitions.length} as const;\nexport const LIFECYCLE_TRANSITIONS = ${JSON.stringify(transitions, null, 2)} as const;\nexport const LIFECYCLE_EVENT_ENTITIES = ${JSON.stringify(Object.fromEntries(lifecycleEventEntities), null, 2)} as const;\nconst transitionKey = (entity: string, from: string, to: string): string => [entity, from, to].join("\\u0000");\nconst transitionKeys = new Set(LIFECYCLE_TRANSITIONS.map(({ entity, from, to }) => transitionKey(entity, from, to)));\nexport function lifecycleEntityForEvent(event: string): string | undefined { return LIFECYCLE_EVENT_ENTITIES[event as keyof typeof LIFECYCLE_EVENT_ENTITIES]; }\nexport function canTransition(entity: string, from: string, to: string): boolean { return transitionKeys.has(transitionKey(entity, from, to)); }\nexport function transitionEvents(entity: string, from: string, to: string): readonly string[] | undefined { return LIFECYCLE_TRANSITIONS.find((t) => t.entity === entity && t.from === from && t.to === to)?.events; }\n`;
const metadataTs = `// Generated by scripts/generate-protocol.mjs; do not edit.\nexport const MAX_RAW_MESSAGE_BYTES = 1_048_576 as const;\nexport const MAX_CONTAINER_DEPTH = 32 as const;\nexport const U64_MAX = "18446744073709551615" as const;\nexport const U128_MAX = "340282366920938463463374607431768211455" as const;\nexport const KNOWN_VARIANTS = ${JSON.stringify(variants, null, 2)} as const;\nexport const PEER_POLICY = ${JSON.stringify(peerPolicy, null, 2)} as const;\nexport const ERROR_RETRY_POLICY = ${JSON.stringify(errorPolicy.retry, null, 2)} as const;\nexport const RUN_PROTOCOL_SCHEMA = ${JSON.stringify(schema, null, 2)} as const;\n`;

const markdownRows = transitions.map((t) => `| ${t.entity} | ${t.from} | ${t.to} | ${t.owner} | ${t.guard} | ${t.events.join(', ')} | ${t.retry} | ${t.reconciliation} | ${t.crash_recovery ?? ''} |`);
const transitionsMarkdown = `# Generated lifecycle transitions\n\nSource: \`schemas/lifecycle-transitions.json\`. This is an allow-list; guards are not executable in the scaffold.\n\nTotal transitions: ${transitions.length}.\n\n| Entity | From | To | Owner | Guard | Durable event | Retry | Reconciliation | Crash recovery |\n|---|---|---|---|---|---|---|---|---|\n${markdownRows.join('\n')}\n`;

const schemaInput = new JSONSchemaInput(new FetchingJSONSchemaStore());
await schemaInput.addSource({ name: schema.title, schema: JSON.stringify(schema) });
const inputData = new InputData();
inputData.addInput(schemaInput);
const rustOutput = await quicktype({ inputData, lang: 'rust', rendererOptions: { edition: '2021' } });
const rustBindings = `// Generated by scripts/generate-protocol.mjs; do not edit.\n${rustOutput.lines.join('\n')}\n`;

const generated = [
  ['crates/runweft-protocol/src/generated.rs', formatRust(rustBindings)],
  ['crates/runweft-protocol/src/generated_metadata.rs', formatRust(metadataRust)],
  ['crates/runweft-protocol/src/generated_transitions.rs', formatRust(transitionsRust)],
  ['packages/protocol/src/generated-metadata.ts', metadataTs],
  ['packages/protocol/src/generated-transitions.ts', transitionsTs],
  ['docs/protocol-transitions.md', transitionsMarkdown],
];
for (const [relative, contents] of generated) {
  const file = path.join(root, relative);
  if (check) {
    if (await readFile(file, 'utf8').catch(() => '') !== contents) throw new Error(`Generated protocol drift: ${relative}`);
  } else {
    await writeFile(file, contents);
  }
}
console.log(check ? 'Generated Rust protocol and metadata are current.' : `Generated protocol metadata and ${transitions.length} lifecycle transitions.`);
