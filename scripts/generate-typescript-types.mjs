// Deterministic TypeScript type emitter for the protocol schema subset.
// quicktype's TypeScript renderer currently recurses without termination on ExtensionValue.
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const schema = JSON.parse(await readFile(path.join(root, 'schemas/run-protocol.schema.json'), 'utf8'));
const refName = (ref) => ref.startsWith('#/$defs/') ? ref.slice('#/$defs/'.length).replaceAll('~1', '/').replaceAll('~0', '~') : null;
const union = (nodes, separator) => [...new Set(nodes.map(typeFor))].join(separator) || 'unknown';

function typeFor(node) {
  if (!node || typeof node !== 'object') return 'unknown';
  if (typeof node.$ref === 'string') return refName(node.$ref) ?? 'unknown';
  if (Object.hasOwn(node, 'const')) return JSON.stringify(node.const);
  if (Array.isArray(node.enum)) return [...new Set(node.enum.map((value) => JSON.stringify(value)))].join(' | ') || 'never';
  const hasObjectShape = node.type === 'object' || node.properties || node.additionalProperties !== undefined;
  const ownObjectType = hasObjectShape ? objectTypeFor(node) : undefined;
  if (Array.isArray(node.allOf)) {
    const parts = [ownObjectType, ...node.allOf.map(typeFor)].filter((type) => type && type !== 'unknown');
    return parts.join(' & ') || 'unknown';
  }
  if (Array.isArray(node.oneOf)) return union(node.oneOf, ' | ');
  if (Array.isArray(node.anyOf)) return union(node.anyOf, ' | ');
  if (node.type === 'array') return `${typeFor(node.items)}[]`;
  if (ownObjectType) return ownObjectType;
  if (Array.isArray(node.type)) return union(node.type.map((type) => ({ type })), ' | ');
  return ({ string: 'string', integer: 'number', number: 'number', boolean: 'boolean', null: 'null' })[node.type] ?? 'unknown';
}

function objectTypeFor(node) {
  const properties = node.properties ?? {};
  const required = new Set(node.required ?? []);
  const entries = Object.entries(properties).map(([name, child]) => `  ${JSON.stringify(name)}${required.has(name) ? '' : '?'}: ${typeFor(child)};`);
  const additional = node.additionalProperties;
  if (additional !== false) {
    const valueType = additional === undefined || additional === true ? 'unknown' : typeFor(additional);
    if (entries.length === 0) return `{ [key: string]: ${valueType} }`;
    entries.push(`  [key: string]: ${valueType};`);
  }
  return entries.length === 0 ? '{ [key: string]: never }' : `{\n${entries.join('\n')}\n}`;
}

const declarations = Object.entries(schema.$defs).map(([name, definition]) => `export type ${name} = ${typeFor(definition)};`);
const output = [
  '// Generated by scripts/generate-protocol.mjs; do not edit.',
  '// Source: schemas/run-protocol.schema.json (JSON Schema Draft 2020-12).',
  ...declarations,
  `export type ${schema.title} = ${typeFor(schema)};`,
  '',
].join('\n');

const check = process.argv.includes('--check');
const file = path.join(root, 'packages/protocol/src/generated.ts');
if (check) {
  if (await readFile(file, 'utf8').catch(() => '') !== output) throw new Error('Generated TypeScript protocol types are stale. Run npm run generate.');
} else {
  await writeFile(file, output);
}
